#!/usr/bin/env tsx
/**
 * test/golden-baseline/golden-baseline.ts - golden regression baseline for Lore's public embedded API.
 *
 * Runs the fixed workload (workload.ts) in a fresh home, normalises volatile fields (normalize.ts), and compares the
 * result with the committed snapshot in snapshots/<engine>.json. A later change that is meant to be default-off must
 * leave these snapshots byte-identical. Steps:
 *   1. determinism guard: run the workload twice in two fresh homes/databases; the normalised outputs must be identical
 *   2. compare to the snapshot (readable diff, first N differing paths) - or, with --update, rewrite it
 *
 *   LORE_HOME=$(mktemp -d) LORE_MODEL_SERVER=0 LORE_GOLDEN_ENGINE=sqlite|postgres tsx test/golden-baseline/golden-baseline.ts [--update]
 *   --update is refused when CI or LORE_FULLCHAIN is set. Postgres needs LORE_PG_URL (otherwise it prints a SKIP line, exit 0).
 */
import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';
import { gateDbUrl } from '../helpers/testPostgres.js';
import { createNormalizer, stableStringify } from './normalize.js';
import { openRun, type Engine } from './open.js';
import { runWorkload } from './workload.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const MAX_DIFFS = 25;

const engine = (process.env['LORE_GOLDEN_ENGINE'] ?? 'sqlite') as Engine;
if (engine !== 'sqlite' && engine !== 'postgres') { console.error(`golden-baseline: LORE_GOLDEN_ENGINE must be sqlite or postgres (got "${engine}")`); process.exit(2); }
const update = process.argv.includes('--update');

/** Error/diff output must never carry the Postgres URL or password. */
function scrub(s: string): string {
    let out = s;
    const raw = gateDbUrl();
    if (raw) {
        out = out.split(raw).join('<pgurl>');
        try { const pw = decodeURIComponent(new URL(raw).password); if (pw) out = out.split(pw).join('<pgpass>'); } catch { /* not a URL */ }
    }
    return out;
}
const die = (e: unknown): never => { console.error(`FAIL golden-baseline:${engine}: ${scrub(String((e as Error)?.stack ?? e))}`); process.exit(1); };
process.on('uncaughtException', die);
process.on('unhandledRejection', die);

if (engine === 'postgres' && !gateDbUrl()) {
    console.log('SKIP golden-baseline:postgres: LORE_PG_URL is not set');
    process.exit(0);
}
if (update && (process.env['CI'] || process.env['LORE_FULLCHAIN'])) {
    console.error('golden-baseline: --update is refused when CI or LORE_FULLCHAIN is set (snapshots are regenerated by hand, never by the chain)');
    process.exit(2);
}

/** One full workload run in a fresh home/database, returned normalised. */
async function once(): Promise<unknown> {
    const run = await openRun(engine);
    let result: unknown;
    try {
        const raw = await runWorkload({ lore: run.lore });
        // Round-trip through JSON first: exactly what a snapshot file can hold (drops functions/undefined, flattens Dates).
        const json = JSON.parse(JSON.stringify(raw));
        result = createNormalizer({ homes: run.homes, tokens: run.tokens }).apply(json);
    } catch (e) {
        // A close() failure must not replace the workload's own error.
        try { await run.close(); } catch (ce) { console.error(`golden-baseline: close() also failed: ${String((ce as Error)?.message ?? ce)}`); }
        throw e;
    }
    await run.close();
    return result;
}

/** Paths (`a.b[3].c`) at which two JSON values differ; stops after `limit`. */
function diffPaths(a: unknown, b: unknown, at = '$', out: string[] = [], limit = MAX_DIFFS): string[] {
    if (out.length >= limit) return out;
    if (JSON.stringify(a) === JSON.stringify(b)) return out;
    const isObj = (x: unknown): x is Record<string, unknown> => !!x && typeof x === 'object';
    if (isObj(a) && isObj(b) && Array.isArray(a) === Array.isArray(b)) {
        for (const k of new Set([...Object.keys(a), ...Object.keys(b)])) {
            const p = Array.isArray(a) ? `${at}[${k}]` : `${at}.${k}`;
            if (!(k in a)) out.push(`${p}: only in actual -> ${short(b[k])}`);
            else if (!(k in b)) out.push(`${p}: only in expected -> ${short(a[k])}`);
            else diffPaths(a[k], b[k], p, out, limit);
            if (out.length >= limit) break;
        }
        return out;
    }
    out.push(`${at}: expected ${short(a)} but got ${short(b)}`);
    return out;
}
const short = (v: unknown): string => { const s = JSON.stringify(v) ?? 'undefined'; return s.length > 160 ? `${s.slice(0, 157)}...` : s; };

const label = `golden-baseline:${engine}`;
const snapFile = path.join(here, 'snapshots', `${engine}.json`);

const first = await once();
const second = await once();
const dg = diffPaths(first, second);
if (dg.length > 0) {
    console.error(`FAIL ${label}: the workload is NOT deterministic (two fresh runs differ after normalisation):`);
    for (const d of dg) console.error(`  ${scrub(d)}`);
    process.exit(1);
}
console.log(`  ok ${label}: determinism guard (two fresh runs identical)`);

const text = stableStringify(first);
if (update) {
    fs.mkdirSync(path.dirname(snapFile), { recursive: true });
    fs.writeFileSync(snapFile, text);
    console.log(`  updated ${path.relative(process.cwd(), snapFile)} (${text.length} bytes)`);
    process.exit(0);
}
if (!fs.existsSync(snapFile)) { console.error(`FAIL ${label}: snapshot ${snapFile} is missing (run with --update, outside CI)`); process.exit(1); }
const expectedText = fs.readFileSync(snapFile, 'utf8');
if (expectedText !== text) {
    const diffs = diffPaths(JSON.parse(expectedText), JSON.parse(text));
    console.error(`FAIL ${label}: output differs from ${path.relative(process.cwd(), snapFile)} (${diffs.length >= MAX_DIFFS ? `first ${MAX_DIFFS}` : 'all'} differing paths):`);
    for (const d of diffs) console.error(`  ${scrub(d)}`);
    console.error('If the change is intended, regenerate with LORE_GOLDEN_ENGINE=' + engine + ' tsx test/golden-baseline/golden-baseline.ts --update (outside CI) and review the diff.');
    process.exit(1);
}
console.log(`  ok ${label}: matches committed snapshot`);
console.log('done');
process.exit(0);
