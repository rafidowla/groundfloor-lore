/**
 * answerModel.ts — the "assistant being tested" for QA generation.
 *
 * Unlike the judge (judge.ts), the paper does NOT fix which model answers
 * the questions — that's the system under test. Competitors' published
 * LongMemEval numbers each use their own reader model; what has to match
 * is the judge. Per this benchmark's task brief: "use whatever model is
 * convenient/available for THIS part... document what you used."
 *
 * This module is a thin, pluggable dispatcher over plain `fetch` (no new
 * npm dependency): OPENAI_API_KEY → gpt-4o-mini (override via
 * generateAnswer()'s modelOverride param / runSubset.ts's --answer-model),
 * else ANTHROPIC_API_KEY → claude-3-5-haiku-latest, else throws
 * AnswerModelUnavailableError.
 *
 * IMPORTANT — 2026-08-12 environment note: neither OPENAI_API_KEY nor
 * ANTHROPIC_API_KEY is set anywhere in the sandbox this harness was built
 * and smoke-tested in (checked: shell env, repo .env/.env.example, no
 * OpenAI/Anthropic credential files on disk). The standalone `claude` CLI
 * binary on this machine is also its own separate, unauthenticated login
 * surface (`claude --print` returned "Not logged in"), so it could not be
 * shelled out to either. For the subset smoke test, real answers were
 * instead generated by hand via the orchestrating agent's own Claude
 * access (i.e., a human/agent in the loop reading retrieved context and
 * answering), NOT via this module — see ../README.md "Answering model" for
 * exactly which questions that covered and why. This module exists so the
 * FULL, unattended, scriptable pipeline is ready the moment either key is
 * exported into the environment.
 */

import { resolveOpenAiGateway } from './openaiGateway.js';
import { fetchWithRetry } from './fetchWithRetry.js';
import { callOllamaChat, isOllamaModel, stripOllamaPrefix, type OllamaThinkMode } from './ollamaClient.js';

export class AnswerModelUnavailableError extends Error {
    constructor(reason: string) {
        super(reason);
        this.name = 'AnswerModelUnavailableError';
    }
}

export interface AnswerModelResult {
    provider: 'openai' | 'anthropic' | 'ollama';
    model: string;
    answer: string;
}

const OPENAI_ANSWER_MODEL = 'gpt-4o-mini';
const ANTHROPIC_ANSWER_MODEL = 'claude-3-5-haiku-latest';

/**
 * Pure prompt builder — exported for unit tests (no API calls).
 *
 * ─── Same-subject rows are not duplicates (2026-08-14) ────────────────────
 *
 * "How many hours have I spent playing games in total?" (gold 140) came back
 * 110 from a structured record that already contained all five numbers. Four
 * of its lines named The Last of Us Part II: two narrative-only, and two
 * numeric — 25 hours (normal difficulty, src `answer_8d015d9d_1::0`) and 30
 * hours (hard difficulty, src `answer_8d015d9d_2::0`). One game, played twice,
 * two real durations. Told only to "sum numeric values", but looking at a
 * cluster of near-identical lines about one game, the model did the sensible-
 * looking thing and counted that game once, keeping the 25 and dropping the 30.
 *
 * The rows were correct, so the fix belongs here rather than in extraction or
 * storage: the answering model needs a rule for reading several lines about
 * one subject. `formatStructuredFacts` now ends each line with the turn it was
 * extracted from, which is what makes the rule decidable — the qualifier line
 * ("on hard difficulty", no number) and the 30 share a src, so they are one
 * occurrence; the 25 has a different src, so it is another. Under the rules
 * below the sum is 30 + 25 + 70 + 10 + 5 = 140.
 *
 * The explicit "a numeric line is never cancelled by a line that merely names
 * the same subject" is the load-bearing half: the observed failure was an
 * under-count, and a merge rule with no floor under it would have made that
 * worse, not better.
 */
export function buildPrompt(
    question: string,
    contextText: string,
    referenceDate: string,
    structuredFacts?: string,
): string {
    const hasStructured = typeof structuredFacts === 'string' && structuredFacts.trim().length > 0;
    const structuredBlock = hasStructured
        ? `\n--- Structured record (authoritative) ---\n${structuredFacts}\n--- End structured record ---\n\n` +
          `When the question asks for a count, total, or ordering, treat the structured record above as authoritative: it was machine-extracted from the full conversation history and may contain items the retrieved excerpts missed. Sum numeric values for totals and count lines for counts. If the structured record is empty or absent, fall back to the retrieved excerpts.\n\n` +
          `Several lines can describe the same subject — the same game, shop, trip, or person — without being duplicates of each other. Before you sum or count, classify each line:\n` +
          `- Lines sharing a src= were extracted from the same sentence. A line naming a qualifier but carrying no number ("on hard difficulty") and a line carrying the number ("value=30") are two halves of ONE occurrence: read them together, count that occurrence once, and use its number.\n` +
          `- Lines with different src= that carry different numbers are ALWAYS separate occurrences, even when the subject is identical. The same game finished twice at two difficulties is two real durations, and both are added.\n` +
          `- A line with no number never cancels a line that has one. Only fold two lines together when they state the same event with no distinguishing number, qualifier, or date between them.\n` +
          `Do not drop a numeric line because some other line mentions the same subject — the usual error here is under-counting, not double-counting.`
        : '';

    return (
        `You are answering a question using ONLY the retrieved conversation excerpts below. ` +
        `These excerpts are turns pulled from a long chat history between a user and an assistant. ` +
        `If the excerpts do not contain enough information to answer, say so plainly rather than guessing. ` +
        `If the excerpts mention different values for the same fact at different points in the conversation ` +
        `(e.g. an amount, a threshold, a status), use the most recently stated value — treat it as having been updated, not contradicted.\n\n` +
        `Today's date is ${referenceDate}.\n\n` +
        `--- Retrieved context ---\n${contextText}\n--- End context ---\n` +
        structuredBlock +
        `\n\nQuestion: ${question}\n\n` +
        `If the question asks how long ago something happened, calculate the elapsed time yourself from the dates given in the excerpts and today's date above — ` +
        `do not say the information is missing just because you don't see the elapsed time already stated outright.\n\n` +
        `Answer concisely, in one or two sentences.`
    );
}

// Some OpenRouter-routed models (e.g. deepseek/deepseek-v4-flash-0731) are
// reasoning models: they spend completion tokens on a hidden chain-of-thought
// BEFORE the visible answer, and that reasoning shares the same max_tokens
// budget as the final content. Confirmed 2026-08-13 via a live probe call:
// a trivial one-sentence question used 152 of 186 completion tokens purely on
// reasoning. A cap tuned for a non-reasoning model (300) starves these models
// before they emit any content at all — finish_reason:"length" with an empty
// message.content, not an API error. 4000 gives real headroom for reasoning
// + answer; the extra ceiling costs nothing for models that don't use it,
// since billing/output is by tokens actually generated, not the cap itself.
const MAX_ANSWER_TOKENS = 4000;

async function callOpenAi(
    apiKey: string,
    question: string,
    contextText: string,
    referenceDate: string,
    model: string,
    structuredFacts?: string,
): Promise<AnswerModelResult> {
    const gateway = resolveOpenAiGateway(apiKey, model);
    const response = await fetchWithRetry(gateway.endpoint, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${apiKey}` },
        body: JSON.stringify({
            model: gateway.modelFor(model),
            messages: [{ role: 'user', content: buildPrompt(question, contextText, referenceDate, structuredFacts) }],
            temperature: 0,
            max_tokens: MAX_ANSWER_TOKENS,
            ...gateway.extraBody,
        }),
    });
    if (!response.ok) {
        const body = await response.text().catch(() => '');
        throw new Error(`OpenAI answer call failed: HTTP ${response.status} ${body.slice(0, 500)}`);
    }
    const json = (await response.json()) as { choices?: Array<{ message?: { content?: string }; finish_reason?: string }> };
    const answer = json.choices?.[0]?.message?.content?.trim();
    if (!answer) {
        const finishReason = json.choices?.[0]?.finish_reason;
        const hint = finishReason === 'length'
            ? ` (finish_reason="length" — likely a reasoning model that used its whole token budget on hidden reasoning before any visible content; raise MAX_ANSWER_TOKENS)`
            : '';
        throw new Error(`Unexpected OpenAI response${hint}: ${JSON.stringify(json).slice(0, 300)}`);
    }
    return { provider: 'openai', model, answer };
}

async function callAnthropic(
    apiKey: string,
    question: string,
    contextText: string,
    referenceDate: string,
    structuredFacts?: string,
): Promise<AnswerModelResult> {
    const response = await fetchWithRetry('https://api.anthropic.com/v1/messages', {
        method: 'POST',
        headers: {
            'Content-Type': 'application/json',
            'x-api-key': apiKey,
            'anthropic-version': '2023-06-01',
        },
        body: JSON.stringify({
            model: ANTHROPIC_ANSWER_MODEL,
            max_tokens: 300,
            temperature: 0,
            messages: [{ role: 'user', content: buildPrompt(question, contextText, referenceDate, structuredFacts) }],
        }),
    });
    if (!response.ok) {
        const body = await response.text().catch(() => '');
        throw new Error(`Anthropic answer call failed: HTTP ${response.status} ${body.slice(0, 500)}`);
    }
    const json = (await response.json()) as { content?: Array<{ type: string; text?: string }> };
    const answer = json.content?.find((b) => b.type === 'text')?.text?.trim();
    if (!answer) throw new Error(`Unexpected Anthropic response: ${JSON.stringify(json).slice(0, 300)}`);
    return { provider: 'anthropic', model: ANTHROPIC_ANSWER_MODEL, answer };
}

async function callOllamaAnswer(
    question: string,
    contextText: string,
    referenceDate: string,
    model: string,
    think: OllamaThinkMode | undefined,
    structuredFacts?: string,
): Promise<AnswerModelResult> {
    const prompt = buildPrompt(question, contextText, referenceDate, structuredFacts);
    const { content } = await callOllamaChat(model, prompt, think);
    return { provider: 'ollama', model, answer: content };
}

export async function generateAnswer(
    question: string,
    contextText: string,
    referenceDate: string,
    modelOverride?: string,
    structuredFacts?: string,
    thinkMode?: OllamaThinkMode,
): Promise<AnswerModelResult> {
    // Local Ollama models (`ollama:<model>`, e.g. `ollama:qwen3.8:27b`) need
    // no API key at all — route them before the key checks below, which
    // exist only to pick between OpenAI and Anthropic.
    if (modelOverride && isOllamaModel(modelOverride)) {
        return callOllamaAnswer(question, contextText, referenceDate, stripOllamaPrefix(modelOverride), thinkMode, structuredFacts);
    }

    const openAiKey = process.env['OPENAI_API_KEY'];
    if (openAiKey) return callOpenAi(openAiKey, question, contextText, referenceDate, modelOverride ?? OPENAI_ANSWER_MODEL, structuredFacts);

    const anthropicKey = process.env['ANTHROPIC_API_KEY'];
    if (anthropicKey) return callAnthropic(anthropicKey, question, contextText, referenceDate, structuredFacts);

    throw new AnswerModelUnavailableError(
        'Neither OPENAI_API_KEY nor ANTHROPIC_API_KEY is set. No scriptable answering model is available in ' +
            'this environment — see answerModel.ts header for what was used instead in the subset smoke test.',
    );
}
