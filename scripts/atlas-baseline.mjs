#!/usr/bin/env -S npx tsx
/**
 * scripts/atlas-baseline.mjs
 *
 * Atlas — capture ms-precision baseline metrics for the parser pipeline.
 * Phase 1 carry-in #5 (deferred from Phase 1, landed at Phase 2 kickoff).
 *
 * Original work authored for groundfloor-lore. License-compliance
 * protocol per `docs/PLAN_replace_gitnexus_in_developer_plugin.md`
 * section 10.
 *
 * Usage:
 *   node scripts/atlas-baseline.mjs [<repo-root> ...]
 *
 * If no repo roots are given, defaults to the lore monorepo itself.
 *
 * Captures:
 *   - parse time per file + per language
 *   - symbol counts per file + per language
 *   - import counts per file + per language
 *   - memory peak (delta vs process start)
 *   - total parseRepo wall-clock duration
 *
 * Output is appended to docs/internal/gitnexus_audit.md as a baseline
 * addendum, and written to stdout as JSON for programmatic consumption.
 */

import * as fs from 'node:fs/promises';
import * as path from 'node:path';
import { performance } from 'node:perf_hooks';
import { fileURLToPath } from 'node:url';
import { parseRepo } from '../packages/lore-plugin-developer/src/parser/index.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, '..');

function memoryPeakMb() {
    const m = process.memoryUsage();
    return Math.round((m.heapUsed + m.external) / (1024 * 1024) * 10) / 10;
}

async function baselineRepo(repoRoot) {
    const startMem = memoryPeakMb();
    const t0 = performance.now();
    const result = await parseRepo(repoRoot);
    const t1 = performance.now();
    const endMem = memoryPeakMb();

    const perLanguage = {};
    for (const file of result.files) {
        const lang = file.language;
        if (!perLanguage[lang]) {
            perLanguage[lang] = {
                files: 0,
                symbols: 0,
                imports: 0,
                totalBytes: 0,
                totalLoc: 0,
            };
        }
        perLanguage[lang].files += 1;
        perLanguage[lang].symbols += file.symbols.length;
        perLanguage[lang].imports += file.imports.length;
        perLanguage[lang].totalBytes += file.sizeBytes;
        perLanguage[lang].totalLoc += file.loc;
    }

    return {
        repoRoot,
        durationMs: Math.round(t1 - t0),
        totalFiles: result.files.length,
        totalSymbols: result.files.reduce((acc, f) => acc + f.symbols.length, 0),
        totalImports: result.files.reduce((acc, f) => acc + f.imports.length, 0),
        skippedFiles: result.skipped.length,
        diagnosticsCount: result.diagnostics.length,
        memoryStartMb: startMem,
        memoryEndMb: endMem,
        memoryDeltaMb: Math.round((endMem - startMem) * 10) / 10,
        perLanguage,
        capturedAt: new Date().toISOString(),
    };
}

function formatMarkdown(reports) {
    const lines = [];
    lines.push('### Atlas baseline — captured ' + new Date().toISOString().slice(0, 10));
    lines.push('');
    lines.push('Generated by `scripts/atlas-baseline.mjs`. One section per repo.');
    lines.push('');
    for (const r of reports) {
        lines.push('#### ' + path.basename(r.repoRoot));
        lines.push('');
        lines.push('- **Path:** `' + r.repoRoot + '`');
        lines.push('- **Total parse time:** ' + r.durationMs + ' ms');
        lines.push('- **Files parsed:** ' + r.totalFiles + ' (skipped: ' + r.skippedFiles + ', diagnostics: ' + r.diagnosticsCount + ')');
        lines.push('- **Total symbols:** ' + r.totalSymbols);
        lines.push('- **Total imports:** ' + r.totalImports);
        lines.push('- **Memory delta:** ' + r.memoryDeltaMb + ' MB (start: ' + r.memoryStartMb + ', end: ' + r.memoryEndMb + ')');
        lines.push('');
        lines.push('Per-language breakdown:');
        lines.push('');
        lines.push('| Language | Files | Symbols | Imports | LOC | Bytes |');
        lines.push('|---|---|---|---|---|---|');
        for (const [lang, stats] of Object.entries(r.perLanguage)) {
            lines.push(`| ${lang} | ${stats.files} | ${stats.symbols} | ${stats.imports} | ${stats.totalLoc} | ${stats.totalBytes} |`);
        }
        lines.push('');
    }
    return lines.join('\n');
}

async function main() {
    const args = process.argv.slice(2);
    const repos = args.length > 0 ? args.map((a) => path.resolve(a)) : [REPO_ROOT];

    const reports = [];
    for (const repo of repos) {
        const exists = await fs.access(repo).then(() => true).catch(() => false);
        if (!exists) {
            console.error(`[atlas-baseline] repo not found: ${repo}`);
            continue;
        }
        console.error(`[atlas-baseline] parsing ${repo}...`);
        const report = await baselineRepo(repo);
        reports.push(report);
        console.error(`[atlas-baseline]   ${report.totalFiles} files, ${report.totalSymbols} symbols, ${report.durationMs} ms`);
    }

    // Append to audit doc.
    const auditPath = path.join(REPO_ROOT, 'docs', 'internal', 'gitnexus_audit.md');
    const md = formatMarkdown(reports);
    try {
        await fs.appendFile(auditPath, '\n\n---\n\n' + md + '\n');
        console.error(`[atlas-baseline] appended baseline section to ${auditPath}`);
    } catch (err) {
        console.error(`[atlas-baseline] could not append to audit doc: ${err.message}`);
    }

    // JSON to stdout for programmatic consumption.
    process.stdout.write(JSON.stringify(reports, null, 2) + '\n');
}

main().catch((err) => {
    console.error('[atlas-baseline] failed:', err);
    process.exit(1);
});
