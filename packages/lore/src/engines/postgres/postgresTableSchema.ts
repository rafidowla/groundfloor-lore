/**
 * postgresTableSchema.ts - Postgres engine: the structured-table (EAV) DDL.
 *
 * Design: docs `TABULAR-AND-COMBINED-QUERY-DESIGN-2026-10-23` section 4. Narrow `entity_value` rows are the source
 * of truth; per-type READ views (postgresTableViews.ts) pivot them back into
 * typed columns. Everything is additive and idempotent (run by
 * `runSchemaBootstrap`, autocommitted), and `workspace_id TEXT NOT NULL` leads
 * every table, key and index - the hard per-workspace boundary.
 *
 *   lore_entity_type   one row per declared table (name unique per workspace)
 *   lore_field_def     one row per declared column; `decl_json` keeps the exact
 *                      ColumnDecl so a schema round-trips byte-for-byte
 *   lore_entity        one row per table row ("entity"): the header carries the
 *                      row key, the optional node/source join keys and the VALID
 *                      time interval [valid_from, valid_to) (NULL = unbounded)
 *   lore_entity_value  one row per (entity, field) value; typed columns, one
 *                      used per row. RECORDED time (recorded_at/superseded_at)
 *                      keeps value history: a change supersedes, never overwrites.
 *
 * Joins: `lore_entity.memory_node_sk` is a real FK to `nodes(sk)` (resolved at
 * write time from the text key `memory_node_id`), so a typed row joins to its
 * node in one statement; `source_id` is a join key to `lore_ingest_sources`
 * (no FK - tables must work without the ingestion schema). Postgres 14 is the
 * floor, so no column-list `ON DELETE SET NULL (col)`.
 */

import type { ColumnType } from '../../contracts/tables.js';

export const TABLE_TABLES = {
    entityType: 'lore_entity_type',
    fieldDef: 'lore_field_def',
    entity: 'lore_entity',
    value: 'lore_entity_value',
    linkType: 'lore_link_type',
    link: 'lore_entity_link',
    settings: 'lore_table_settings',
    alias: 'lore_entity_alias',
} as const;

/** Per-type read-view name prefix (`lore_tv_<entity_type_id>`; ids are globally unique). */
export const TABLE_VIEW_PREFIX = 'lore_tv_';

/** Columns the view always exposes for joins/as-of; user columns may not start with this. */
export const HEADER_COLUMN_PREFIX = '_lore_';

/** Which typed `lore_entity_value` column holds each declared ColumnType. */
export const VALUE_COLUMN: Record<ColumnType, string> = {
    string: 'v_text',
    integer: 'v_int',
    float: 'v_num',
    boolean: 'v_bool',
    date: 'v_date',
    datetime: 'v_ts',
    json: 'v_json',
    money: 'v_amount', // the currency half lives in v_currency (CURRENCY_COLUMN)
};

/** `money` columns keep their currency in this typed `lore_entity_value` column. */
export const CURRENCY_COLUMN = 'v_currency';

/** A money column `price` is exposed on the read view as `price` (amount) plus `price__currency`. */
export const CURRENCY_SUFFIX = '__currency';

/** SQL type used to cast bound params / unnest arrays, per ColumnType. */
export const PG_TYPE: Record<ColumnType, string> = {
    string: 'text',
    integer: 'bigint',
    float: 'double precision',
    boolean: 'boolean',
    date: 'date',
    datetime: 'timestamptz',
    json: 'jsonb',
    money: 'numeric',
};

export function tableSchemaDdl(): string[] {
    const { entityType, fieldDef, entity, value } = TABLE_TABLES;
    return [
        `CREATE TABLE IF NOT EXISTS ${entityType} (
    workspace_id   TEXT NOT NULL,
    entity_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name           TEXT NOT NULL,
    description    TEXT,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (workspace_id, entity_type_id),
    UNIQUE (workspace_id, name)
)`,
        `CREATE TABLE IF NOT EXISTS ${fieldDef} (
    workspace_id   TEXT NOT NULL,
    field_id       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    entity_type_id BIGINT NOT NULL,
    name           TEXT NOT NULL,
    data_type      TEXT NOT NULL,
    flags          TEXT NOT NULL DEFAULT '',
    position       INTEGER NOT NULL,
    decl_json      TEXT NOT NULL,
    PRIMARY KEY (workspace_id, field_id),
    UNIQUE (workspace_id, entity_type_id, name),
    FOREIGN KEY (workspace_id, entity_type_id) REFERENCES ${entityType} (workspace_id, entity_type_id) ON DELETE CASCADE
)`,
        `CREATE TABLE IF NOT EXISTS ${entity} (
    workspace_id   TEXT NOT NULL,
    entity_id      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    entity_type_id BIGINT NOT NULL,
    pk_text        TEXT NOT NULL,
    memory_node_id TEXT,
    memory_node_sk BIGINT REFERENCES nodes (sk) ON DELETE SET NULL,
    valid_from     TIMESTAMPTZ,
    valid_to       TIMESTAMPTZ,
    source_id      TEXT,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (workspace_id, entity_id),
    CONSTRAINT lore_entity_pk_uq UNIQUE (workspace_id, entity_type_id, pk_text),
    FOREIGN KEY (workspace_id, entity_type_id) REFERENCES ${entityType} (workspace_id, entity_type_id) ON DELETE CASCADE
)`,
        `CREATE INDEX IF NOT EXISTS lore_entity_type_order_idx ON ${entity} (workspace_id, entity_type_id, entity_id)`,
        `CREATE INDEX IF NOT EXISTS lore_entity_source_idx ON ${entity} (workspace_id, entity_type_id, source_id)`,
        `CREATE INDEX IF NOT EXISTS lore_entity_node_idx ON ${entity} (workspace_id, memory_node_id) WHERE memory_node_id IS NOT NULL`,
        `CREATE INDEX IF NOT EXISTS lore_entity_node_sk_idx ON ${entity} (memory_node_sk) WHERE memory_node_sk IS NOT NULL`,
        `CREATE TABLE IF NOT EXISTS ${value} (
    workspace_id  TEXT NOT NULL,
    value_id      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    entity_id     BIGINT NOT NULL,
    field_id      BIGINT NOT NULL,
    v_text        TEXT,
    v_int         BIGINT,
    v_num         DOUBLE PRECISION,
    v_bool        BOOLEAN,
    v_date        DATE,
    v_ts          TIMESTAMPTZ,
    v_json        JSONB,
    recorded_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    superseded_at TIMESTAMPTZ,
    PRIMARY KEY (workspace_id, value_id),
    FOREIGN KEY (workspace_id, entity_id) REFERENCES ${entity} (workspace_id, entity_id) ON DELETE CASCADE,
    FOREIGN KEY (workspace_id, field_id) REFERENCES ${fieldDef} (workspace_id, field_id) ON DELETE CASCADE
)`,
        // One CURRENT value per (entity, field); history rows have superseded_at set and fall out of the index.
        `CREATE UNIQUE INDEX IF NOT EXISTS lore_ev_current_uq ON ${value} (workspace_id, entity_id, field_id) WHERE superseded_at IS NULL`,
        `CREATE INDEX IF NOT EXISTS lore_ev_field_idx ON ${value} (workspace_id, field_id)`,
        ...valueSlice2Ddl(),
        ...tableLinkDdl(),
        ...tableReviewDdl(),
    ];
}

/**
 * Slice 2 additions to `lore_entity_value`: the money value kind (amount + currency) and the per-value
 * provenance columns (design 4.3). Every statement is additive and idempotent, so a slice-1 (3.36.0)
 * database upgrades in place; all columns are nullable so existing rows stay valid.
 */
export function valueSlice2Ddl(): string[] {
    const { value } = TABLE_TABLES;
    return [
        `ALTER TABLE ${value} ADD COLUMN IF NOT EXISTS v_amount NUMERIC`,
        `ALTER TABLE ${value} ADD COLUMN IF NOT EXISTS v_currency CHAR(3)`,
        // Money is a pair: both halves set or both NULL, and the currency is three upper-case letters.
        `DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'lore_ev_money_ck' AND conrelid = '${value}'::regclass) THEN
        ALTER TABLE ${value} ADD CONSTRAINT lore_ev_money_ck
            CHECK ((v_amount IS NULL) = (v_currency IS NULL) AND (v_currency IS NULL OR v_currency ~ '^[A-Z]{3}$'));
    END IF;
END $$`,
        `ALTER TABLE ${value} ADD COLUMN IF NOT EXISTS source_document_id TEXT`,
        `ALTER TABLE ${value} ADD COLUMN IF NOT EXISTS source_page INTEGER`,
        `ALTER TABLE ${value} ADD COLUMN IF NOT EXISTS verified_quote TEXT`,
        `ALTER TABLE ${value} ADD COLUMN IF NOT EXISTS confidence DOUBLE PRECISION CHECK (confidence IS NULL OR (confidence >= 0 AND confidence <= 1))`,
        `ALTER TABLE ${value} ADD COLUMN IF NOT EXISTS needs_review BOOLEAN`,
        `ALTER TABLE ${value} ADD COLUMN IF NOT EXISTS extractor TEXT`,
        `ALTER TABLE ${value} ADD COLUMN IF NOT EXISTS contract TEXT`,
        `ALTER TABLE ${value} ADD COLUMN IF NOT EXISTS extracted_at TIMESTAMPTZ`,
        `ALTER TABLE ${value} ADD COLUMN IF NOT EXISTS reviewed_by TEXT`,
        `ALTER TABLE ${value} ADD COLUMN IF NOT EXISTS reviewed_at TIMESTAMPTZ`,
        // "Open the source of any number" and the review queue.
        `CREATE INDEX IF NOT EXISTS lore_ev_source_doc_idx ON ${value} (workspace_id, source_document_id) WHERE source_document_id IS NOT NULL`,
        `CREATE INDEX IF NOT EXISTS lore_ev_review_idx ON ${value} (workspace_id, field_id) WHERE needs_review AND superseded_at IS NULL`,
    ];
}

/**
 * Typed record links (design 4.1/4.2). `from_unique` / `to_unique` are denormalised from the link type's
 * cardinality (immutable once defined) so the database itself enforces it with partial unique indexes over the
 * OPEN links (valid_to IS NULL) - a closed link is history and never blocks a new one.
 */
export function tableLinkDdl(): string[] {
    const { entityType, entity, linkType, link } = TABLE_TABLES;
    return [
        `CREATE TABLE IF NOT EXISTS ${linkType} (
    workspace_id    TEXT NOT NULL,
    link_type_id    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name            TEXT NOT NULL,
    from_type_id    BIGINT NOT NULL,
    to_type_id      BIGINT NOT NULL,
    cardinality     TEXT NOT NULL CHECK (cardinality IN ('one_to_one', 'one_to_many', 'many_to_one', 'many_to_many')),
    description     TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (workspace_id, link_type_id),
    UNIQUE (workspace_id, name),
    FOREIGN KEY (workspace_id, from_type_id) REFERENCES ${entityType} (workspace_id, entity_type_id) ON DELETE CASCADE,
    FOREIGN KEY (workspace_id, to_type_id) REFERENCES ${entityType} (workspace_id, entity_type_id) ON DELETE CASCADE
)`,
        `CREATE TABLE IF NOT EXISTS ${link} (
    workspace_id      TEXT NOT NULL,
    link_id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    link_type_id      BIGINT NOT NULL,
    from_entity_id    BIGINT NOT NULL,
    to_entity_id      BIGINT NOT NULL,
    origin            TEXT NOT NULL DEFAULT 'manual',
    policy_version    TEXT,
    model_fingerprint TEXT,
    confidence        DOUBLE PRECISION CHECK (confidence IS NULL OR (confidence >= 0 AND confidence <= 1)),
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    valid_from        TIMESTAMPTZ,
    valid_to          TIMESTAMPTZ,
    from_unique       BOOLEAN NOT NULL DEFAULT false,
    to_unique         BOOLEAN NOT NULL DEFAULT false,
    PRIMARY KEY (workspace_id, link_id),
    CHECK (valid_from IS NULL OR valid_to IS NULL OR valid_to > valid_from),
    FOREIGN KEY (workspace_id, link_type_id) REFERENCES ${linkType} (workspace_id, link_type_id) ON DELETE CASCADE,
    FOREIGN KEY (workspace_id, from_entity_id) REFERENCES ${entity} (workspace_id, entity_id) ON DELETE CASCADE,
    FOREIGN KEY (workspace_id, to_entity_id) REFERENCES ${entity} (workspace_id, entity_id) ON DELETE CASCADE
)`,
        `CREATE UNIQUE INDEX IF NOT EXISTS lore_link_open_uq ON ${link} (workspace_id, link_type_id, from_entity_id, to_entity_id) WHERE valid_to IS NULL`,
        `CREATE UNIQUE INDEX IF NOT EXISTS lore_link_from_uq ON ${link} (workspace_id, link_type_id, from_entity_id) WHERE valid_to IS NULL AND from_unique`,
        `CREATE UNIQUE INDEX IF NOT EXISTS lore_link_to_uq ON ${link} (workspace_id, link_type_id, to_entity_id) WHERE valid_to IS NULL AND to_unique`,
        `CREATE INDEX IF NOT EXISTS lore_link_from_idx ON ${link} (workspace_id, from_entity_id)`,
        `CREATE INDEX IF NOT EXISTS lore_link_to_idx ON ${link} (workspace_id, to_entity_id)`,
    ];
}

/**
 * Review queue + alias table (design 5.1 steps 5-6, section 9 Q5). Everything is additive and idempotent, so a 3.36.0
 * (or current main) database upgrades in place:
 *   - `lore_table_settings`  one row per workspace: the review confidence threshold (absent row = the default).
 *   - `lore_entity_value.supersedes_value_id`  set on a value row written by a review (confirm/correct) to the
 *     extractor row it replaced, so the history reads as a chain and a repeated confirm is recognised.
 *   - `lore_ev_unreviewed_idx`  the queue scan (open, unreviewed values that are flagged or carry a confidence).
 *   - `lore_entity_alias`  per-workspace alias -> canonical spellings for one table column. Removing an alias sets
 *     `valid_to` (history stays); at most one OPEN alias per (column, normalised spelling).
 */
export function tableReviewDdl(): string[] {
    const { value, fieldDef, settings, alias } = TABLE_TABLES;
    return [
        `CREATE TABLE IF NOT EXISTS ${settings} (
    workspace_id                 TEXT PRIMARY KEY,
    review_confidence_threshold  DOUBLE PRECISION NOT NULL CHECK (review_confidence_threshold >= 0 AND review_confidence_threshold <= 1),
    updated_at                   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by                   TEXT
)`,
        `ALTER TABLE ${value} ADD COLUMN IF NOT EXISTS supersedes_value_id BIGINT`,
        `CREATE INDEX IF NOT EXISTS lore_ev_unreviewed_idx ON ${value} (workspace_id, field_id, value_id)
    WHERE superseded_at IS NULL AND reviewed_at IS NULL AND (needs_review IS TRUE OR confidence IS NOT NULL)`,
        `CREATE TABLE IF NOT EXISTS ${alias} (
    workspace_id    TEXT NOT NULL,
    alias_id        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    field_id        BIGINT NOT NULL,
    alias_norm      TEXT NOT NULL,
    alias_raw       TEXT NOT NULL,
    canonical_norm  TEXT NOT NULL,
    canonical       TEXT NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by      TEXT,
    valid_to        TIMESTAMPTZ,
    removed_by      TEXT,
    PRIMARY KEY (workspace_id, alias_id),
    CHECK (alias_norm <> '' AND canonical_norm <> ''),
    FOREIGN KEY (workspace_id, field_id) REFERENCES ${fieldDef} (workspace_id, field_id) ON DELETE CASCADE
)`,
        `CREATE UNIQUE INDEX IF NOT EXISTS lore_alias_open_uq ON ${alias} (workspace_id, field_id, alias_norm) WHERE valid_to IS NULL`,
        `CREATE INDEX IF NOT EXISTS lore_alias_canonical_idx ON ${alias} (workspace_id, field_id, canonical_norm) WHERE valid_to IS NULL`,
    ];
}
