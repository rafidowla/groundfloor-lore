/**
 * postgresTableSchema.ts - Postgres engine: the structured-table (EAV) DDL.
 *
 * Design: docs `TABULAR-AND-COMBINED-QUERY-DESIGN-2026-10-23` section 4. Narrow `entity_value` rows are the source
 * of truth; per-type READ views (postgresTableViews.ts) pivot them back into
 * typed columns. Everything is additive and idempotent (run by
 * `runSchemaBootstrap`, autocommitted), and `workspace_id TEXT NOT NULL` leads
 * every table, key and index - the hard per-workspace boundary.
 *
 *   lore_entity_type   one row per declared table (name unique per workspace)
 *   lore_field_def     one row per declared column; `decl_json` keeps the exact
 *                      ColumnDecl so a schema round-trips byte-for-byte
 *   lore_entity        one row per table row ("entity"): the header carries the
 *                      row key, the optional node/source join keys and the VALID
 *                      time interval [valid_from, valid_to) (NULL = unbounded)
 *   lore_entity_value  one row per (entity, field) value; typed columns, one
 *                      used per row. RECORDED time (recorded_at/superseded_at)
 *                      keeps value history: a change supersedes, never overwrites.
 *
 * Joins: `lore_entity.memory_node_sk` is a real FK to `nodes(sk)` (resolved at
 * write time from the text key `memory_node_id`), so a typed row joins to its
 * node in one statement; `source_id` is a join key to `lore_ingest_sources`
 * (no FK - tables must work without the ingestion schema). Postgres 14 is the
 * floor, so no column-list `ON DELETE SET NULL (col)`.
 */

import type { ColumnType } from '../../contracts/tables.js';

export const TABLE_TABLES = {
    entityType: 'lore_entity_type',
    fieldDef: 'lore_field_def',
    entity: 'lore_entity',
    value: 'lore_entity_value',
} as const;

/** Per-type read-view name prefix (`lore_tv_<entity_type_id>`; ids are globally unique). */
export const TABLE_VIEW_PREFIX = 'lore_tv_';

/** Columns the view always exposes for joins/as-of; user columns may not start with this. */
export const HEADER_COLUMN_PREFIX = '_lore_';

/** Which typed `lore_entity_value` column holds each declared ColumnType. */
export const VALUE_COLUMN: Record<ColumnType, string> = {
    string: 'v_text',
    integer: 'v_int',
    float: 'v_num',
    boolean: 'v_bool',
    date: 'v_date',
    datetime: 'v_ts',
    json: 'v_json',
};

/** SQL type used to cast bound params / unnest arrays, per ColumnType. */
export const PG_TYPE: Record<ColumnType, string> = {
    string: 'text',
    integer: 'bigint',
    float: 'double precision',
    boolean: 'boolean',
    date: 'date',
    datetime: 'timestamptz',
    json: 'jsonb',
};

export function tableSchemaDdl(): string[] {
    const { entityType, fieldDef, entity, value } = TABLE_TABLES;
    return [
        `CREATE TABLE IF NOT EXISTS ${entityType} (
    workspace_id   TEXT NOT NULL,
    entity_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name           TEXT NOT NULL,
    description    TEXT,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (workspace_id, entity_type_id),
    UNIQUE (workspace_id, name)
)`,
        `CREATE TABLE IF NOT EXISTS ${fieldDef} (
    workspace_id   TEXT NOT NULL,
    field_id       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    entity_type_id BIGINT NOT NULL,
    name           TEXT NOT NULL,
    data_type      TEXT NOT NULL,
    flags          TEXT NOT NULL DEFAULT '',
    position       INTEGER NOT NULL,
    decl_json      TEXT NOT NULL,
    PRIMARY KEY (workspace_id, field_id),
    UNIQUE (workspace_id, entity_type_id, name),
    FOREIGN KEY (workspace_id, entity_type_id) REFERENCES ${entityType} (workspace_id, entity_type_id) ON DELETE CASCADE
)`,
        `CREATE TABLE IF NOT EXISTS ${entity} (
    workspace_id   TEXT NOT NULL,
    entity_id      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    entity_type_id BIGINT NOT NULL,
    pk_text        TEXT NOT NULL,
    memory_node_id TEXT,
    memory_node_sk BIGINT REFERENCES nodes (sk) ON DELETE SET NULL,
    valid_from     TIMESTAMPTZ,
    valid_to       TIMESTAMPTZ,
    source_id      TEXT,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (workspace_id, entity_id),
    CONSTRAINT lore_entity_pk_uq UNIQUE (workspace_id, entity_type_id, pk_text),
    FOREIGN KEY (workspace_id, entity_type_id) REFERENCES ${entityType} (workspace_id, entity_type_id) ON DELETE CASCADE
)`,
        `CREATE INDEX IF NOT EXISTS lore_entity_type_order_idx ON ${entity} (workspace_id, entity_type_id, entity_id)`,
        `CREATE INDEX IF NOT EXISTS lore_entity_source_idx ON ${entity} (workspace_id, entity_type_id, source_id)`,
        `CREATE INDEX IF NOT EXISTS lore_entity_node_idx ON ${entity} (workspace_id, memory_node_id) WHERE memory_node_id IS NOT NULL`,
        `CREATE INDEX IF NOT EXISTS lore_entity_node_sk_idx ON ${entity} (memory_node_sk) WHERE memory_node_sk IS NOT NULL`,
        `CREATE TABLE IF NOT EXISTS ${value} (
    workspace_id  TEXT NOT NULL,
    value_id      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    entity_id     BIGINT NOT NULL,
    field_id      BIGINT NOT NULL,
    v_text        TEXT,
    v_int         BIGINT,
    v_num         DOUBLE PRECISION,
    v_bool        BOOLEAN,
    v_date        DATE,
    v_ts          TIMESTAMPTZ,
    v_json        JSONB,
    recorded_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    superseded_at TIMESTAMPTZ,
    PRIMARY KEY (workspace_id, value_id),
    FOREIGN KEY (workspace_id, entity_id) REFERENCES ${entity} (workspace_id, entity_id) ON DELETE CASCADE,
    FOREIGN KEY (workspace_id, field_id) REFERENCES ${fieldDef} (workspace_id, field_id) ON DELETE CASCADE
)`,
        // One CURRENT value per (entity, field); history rows have superseded_at set and fall out of the index.
        `CREATE UNIQUE INDEX IF NOT EXISTS lore_ev_current_uq ON ${value} (workspace_id, entity_id, field_id) WHERE superseded_at IS NULL`,
        `CREATE INDEX IF NOT EXISTS lore_ev_field_idx ON ${value} (workspace_id, field_id)`,
    ];
}
